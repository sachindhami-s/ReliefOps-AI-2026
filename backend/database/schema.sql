PRAGMA foreign_keys = ON;

-- 1. Disaster Events
CREATE TABLE IF NOT EXISTS disaster_events (
    event_id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    disaster_type TEXT NOT NULL CHECK(disaster_type IN ('FLOOD', 'EARTHQUAKE', 'CYCLONE', 'LANDSLIDE')),
    severity_level TEXT NOT NULL CHECK(severity_level IN ('MODERATE', 'SEVERE', 'CATASTROPHIC')),
    reported_at DATETIME NOT NULL,
    status TEXT NOT NULL CHECK(status IN ('ACTIVE', 'RE-PLANNING', 'RESOLVED', 'ARCHIVED')),
    total_affected_pop INTEGER NOT NULL CHECK(total_affected_pop >= 0)
);

-- 2. Affected Zones
CREATE TABLE IF NOT EXISTS affected_zones (
    zone_id TEXT PRIMARY KEY,
    event_id TEXT NOT NULL,
    name TEXT NOT NULL,
    latitude REAL NOT NULL,
    longitude REAL NOT NULL,
    population INTEGER NOT NULL CHECK(population > 0),
    vulnerability_index REAL NOT NULL CHECK(vulnerability_index >= 0.0 AND vulnerability_index <= 1.0),
    damage_level INTEGER NOT NULL CHECK(damage_level BETWEEN 1 AND 5),
    medical_urgency REAL NOT NULL CHECK(medical_urgency >= 0.0 AND medical_urgency <= 1.0),
    access_status TEXT NOT NULL CHECK(access_status IN ('OPEN', 'DEGRADED', 'BLOCKED', 'AIR_ONLY')),
    calculated_priority REAL DEFAULT 0.0,
    FOREIGN KEY (event_id) REFERENCES disaster_events(event_id) ON DELETE CASCADE
);

-- 3. Warehouses / Logistics Hubs
CREATE TABLE IF NOT EXISTS warehouses (
    warehouse_id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    latitude REAL NOT NULL,
    longitude REAL NOT NULL,
    status TEXT NOT NULL CHECK(status IN ('OPERATIONAL', 'CAPACITY_WARNING', 'INACCESSIBLE')),
    total_capacity_m3 REAL NOT NULL CHECK(total_capacity_m3 > 0)
);

-- 4. Warehouse Inventory
CREATE TABLE IF NOT EXISTS warehouse_inventory (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    warehouse_id TEXT NOT NULL,
    resource_type TEXT NOT NULL CHECK(resource_type IN ('FOOD_RATIONS', 'CLEAN_WATER', 'MEDICAL_KITS', 'SHELTER_TENTS')),
    available_quantity INTEGER NOT NULL CHECK(available_quantity >= 0),
    reserved_quantity INTEGER NOT NULL DEFAULT 0 CHECK(reserved_quantity >= 0),
    unit TEXT NOT NULL,
    last_updated DATETIME NOT NULL,
    FOREIGN KEY (warehouse_id) REFERENCES warehouses(warehouse_id) ON DELETE CASCADE,
    UNIQUE(warehouse_id, resource_type)
);

-- 5. Allocation Plans
CREATE TABLE IF NOT EXISTS allocation_plans (
    plan_id TEXT PRIMARY KEY,
    event_id TEXT NOT NULL,
    iteration INTEGER NOT NULL DEFAULT 1,
    status TEXT NOT NULL CHECK(status IN ('DRAFT', 'AUDITING', 'REVISION_REQUIRED', 'APPROVED', 'RELEASED', 'REJECTED')),
    fairness_score REAL DEFAULT 0.0,
    approved_by TEXT DEFAULT NULL,
    created_at DATETIME NOT NULL,
    approved_at DATETIME DEFAULT NULL,
    FOREIGN KEY (event_id) REFERENCES disaster_events(event_id) ON DELETE CASCADE
);

-- 6. Itemized Allocation Dispatches
CREATE TABLE IF NOT EXISTS allocation_items (
    item_id INTEGER PRIMARY KEY AUTOINCREMENT,
    plan_id TEXT NOT NULL,
    zone_id TEXT NOT NULL,
    warehouse_id TEXT NOT NULL,
    resource_type TEXT NOT NULL,
    requested_qty INTEGER NOT NULL CHECK(requested_qty >= 0),
    allocated_qty INTEGER NOT NULL CHECK(allocated_qty >= 0),
    distance_km REAL NOT NULL,
    est_transit_hours REAL NOT NULL,
    FOREIGN KEY (plan_id) REFERENCES allocation_plans(plan_id) ON DELETE CASCADE,
    FOREIGN KEY (zone_id) REFERENCES affected_zones(zone_id),
    FOREIGN KEY (warehouse_id) REFERENCES warehouses(warehouse_id)
);

-- 7. Audit Logs (Generated by Fairness Auditor Agent)
CREATE TABLE IF NOT EXISTS audit_logs (
    audit_id INTEGER PRIMARY KEY AUTOINCREMENT,
    plan_id TEXT NOT NULL,
    auditor_agent TEXT NOT NULL,
    verdict TEXT NOT NULL CHECK(verdict IN ('APPROVED', 'REJECTED', 'WARNING_OVERRIDDEN')),
    gini_coefficient REAL NOT NULL,
    min_coverage_ratio REAL NOT NULL,
    violations_json TEXT NOT NULL,
    explanation TEXT NOT NULL,
    audited_at DATETIME NOT NULL,
    FOREIGN KEY (plan_id) REFERENCES allocation_plans(plan_id) ON DELETE CASCADE
);

-- 8. Blackboard Event Journal (Append-only state audit trail)
CREATE TABLE IF NOT EXISTS blackboard_events (
    event_seq INTEGER PRIMARY KEY AUTOINCREMENT,
    plan_id TEXT NOT NULL,
    agent_name TEXT NOT NULL,
    action_type TEXT NOT NULL,
    target_section TEXT NOT NULL,
    payload_json TEXT NOT NULL,
    timestamp DATETIME NOT NULL
);

-- 9. SOP Document Metadata
CREATE TABLE IF NOT EXISTS sop_documents (
    doc_id TEXT PRIMARY KEY,
    title TEXT NOT NULL,
    disaster_type TEXT NOT NULL,
    source_agency TEXT NOT NULL,
    chunk_count INTEGER NOT NULL DEFAULT 0,
    chromadb_collection TEXT NOT NULL,
    ingested_at DATETIME NOT NULL
);

-- 10. Simulation Scenarios
CREATE TABLE IF NOT EXISTS simulation_scenarios (
    scenario_id TEXT PRIMARY KEY,
    title TEXT NOT NULL,
    description TEXT NOT NULL,
    scenario_type TEXT NOT NULL,
    parameters_json TEXT NOT NULL,
    created_at DATETIME NOT NULL
);

-- Indexes for performance
CREATE INDEX IF NOT EXISTS idx_zones_event ON affected_zones(event_id);
CREATE INDEX IF NOT EXISTS idx_inv_warehouse ON warehouse_inventory(warehouse_id);
CREATE INDEX IF NOT EXISTS idx_alloc_plan ON allocation_items(plan_id);
CREATE INDEX IF NOT EXISTS idx_blackboard_plan ON blackboard_events(plan_id);
CREATE INDEX IF NOT EXISTS idx_audit_plan ON audit_logs(plan_id);

